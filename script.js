function createCheckboxes(
    containerId,
    items,
    storageKey
) {

    const container =
        document.getElementById(
            containerId
        );

    container.innerHTML = "";


    items.forEach(
        (item, index) => {

            const label =
                document.createElement(
                    "label"
                );

            label.classList.add(
                "check-item"
            );


            const checkbox =
                document.createElement(
                    "input"
                );

            checkbox.type =
                "checkbox";


            const key =
                `${storageKey}-${index}`;


            checkbox.checked =
                completedTopics[key] ||
                false;


            checkbox.addEventListener(
                "change",
                () => {

                    completedTopics[key] =
                        checkbox.checked;


                    localStorage.setItem(
                        "completedTopics",
                        JSON.stringify(
                            completedTopics
                        )
                    );


                    updateProgress();

                }
            );


            const text =
                document.createElement(
                    "span"
                );

            text.textContent =
                item;


            label.appendChild(
                checkbox
            );

            label.appendChild(
                text
            );


            container.appendChild(
                label
            );

        }
    );

}


