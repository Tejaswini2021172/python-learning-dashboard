function getDayNumber(date) {

    const start =
        new Date(
            startDate.getFullYear(),
            startDate.getMonth(),
            startDate.getDate()
        );

    const selected =
        new Date(
            date.getFullYear(),
            date.getMonth(),
            date.getDate()
        );

    const difference =
        selected - start;

    const days =
        Math.floor(
            difference / (1000 * 60 * 60 * 24)
        );

    return days + 1;
}


function renderCalendar() {

    calendar.innerHTML = "";

    const year =
        currentDate.getFullYear();

    const month =
        currentDate.getMonth();

    const firstDay =
        new Date(year, month, 1);

    const lastDay =
        new Date(year, month + 1, 0);


    let startDay =
        firstDay.getDay();

    if (startDay === 0) {

        startDay = 6;

    } else {

        startDay--;

    }


    monthYear.textContent =
        currentDate.toLocaleString(
            "default",
            {
                month: "long",
                year: "numeric"
            }
        );


    for (let i = 0; i < startDay; i++) {

        const empty =
            document.createElement("div");

        empty.classList.add("empty");

        calendar.appendChild(empty);

    }


    const today =
        new Date();


    for (
        let day = 1;
        day <= lastDay.getDate();
        day++
    ) {

        const date =
            new Date(year, month, day);

        const dayNumber =
            getDayNumber(date);


        const dayElement =
            document.createElement("div");

        dayElement.classList.add("day");


        const number =
            document.createElement("div");

        number.classList.add("day-number");

        number.textContent = day;

        dayElement.appendChild(number);


        /*
        CHECK IF DATE IS INSIDE
        THE 30-DAY LEARNING PLAN
        */

        if (
            dayNumber >= 1 &&
            dayNumber <= totalDays
        ) {

            const topic =
                document.createElement("div");

            topic.classList.add("day-topic");

            topic.textContent =
                `Day ${dayNumber}`;

            dayElement.appendChild(topic);


            if (
                completedDays.includes(dayNumber)
            ) {

                dayElement.classList.add(
                    "completed"
                );

            }


            if (
                selectedDay === dayNumber
            ) {

                dayElement.classList.add(
                    "selected"
                );

            }


            dayElement.addEventListener(
                "click",
                () => {

                    showDay(dayNumber);

                }
            );

        } else {

            dayElement.style.cursor =
                "default";

            dayElement.style.opacity =
                "0.5";

        }


        /*
        HIGHLIGHT TODAY
        */

        if (
            day === today.getDate() &&
            month === today.getMonth() &&
            year === today.getFullYear()
        ) {

            dayElement.classList.add(
                "today"
            );

        }


        calendar.appendChild(dayElement);

    }

}


